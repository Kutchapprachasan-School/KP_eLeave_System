import fs from 'node:fs';
import path from 'node:path';

const ROOT_DIR = process.cwd();
const OUTPUT_FILE = path.join(ROOT_DIR, 'CODEBASE_INDEX.md');
const PRISMA_SCHEMA = path.join(ROOT_DIR, 'prisma', 'schema.prisma');

// โฟลเดอร์เป้าหมายที่ต้องการสแกน (ปรับเพิ่มลดได้ตามโครงสร้างโปรเจกต์)
const TARGET_DIRS = ['src', 'app', 'lib', 'services', 'actions', 'components', 'utils', 'hooks'];
const IGNORE_DIRS = new Set(['node_modules', '.next', '.git', 'scratch', 'dist', 'build', 'coverage']);
const VALID_EXTS = new Set(['.ts', '.tsx']);

/**
 * คำนวณบรรทัดสิ้นสุดของบล็อกโค้ดด้วยการนับวงเล็บปีกกา { ... }
 */
function findBlockEndLine(lines, startIndex) {
  let braceCount = 0;
  let foundOpenBrace = false;

  for (let i = startIndex; i < lines.length; i++) {
    // ตัด comment ท้ายบรรทัดและข้อความใน string ออกอย่างง่ายเพื่อไม่ให้นับปีกกาผิด
    const cleanLine = lines[i]
      .replace(/\/\/.*$/, '')
      .replace(/(['"`])(?:(?=(\\?))\2.)*?\1/g, '');

    for (const char of cleanLine) {
      if (char === '{') {
        braceCount++;
        foundOpenBrace = true;
      } else if (char === '}') {
        braceCount--;
      }
    }

    if (foundOpenBrace && braceCount <= 0) {
      return i + 1; // คืนค่าเลขบรรทัดแบบ 1-based
    }

    // กรณีเป็น type หรือ const แบบบรรทัดเดียวจบด้วย ;
    if (!foundOpenBrace && cleanLine.trim().endsWith(';')) {
      return i + 1;
    }
  }
  return startIndex + 1;
}

/**
 * สแกนไฟล์ prisma/schema.prisma เพื่อดึงพิกัดบรรทัดของ Model และ Enum
 */
function parsePrismaSchema(schemaPath) {
  if (!fs.existsSync(schemaPath)) return [];
  const content = fs.readFileSync(schemaPath, 'utf8');
  const lines = content.split(/\r?\n/);
  const items = [];

  const regex = /^\s*(model|enum)\s+([A-Za-z0-9_]+)\s*\{/;
  for (let i = 0; i < lines.length; i++) {
    const match = lines[i].match(regex);
    if (match) {
      const kind = match[1];
      const name = match[2];
      const startLine = i + 1;
      const endLine = findBlockEndLine(lines, i);
      items.push({ kind, name, startLine, endLine });
    }
  }
  return { totalLines: lines.length, items };
}

/**
 * สแกนไฟล์ .ts / .tsx เพื่อดึงพิกัดบรรทัดของ Exported Symbols และฟังก์ชันหลัก
 */
function parseTypeScriptFile(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split(/\r?\n/);
  const symbols = [];

  const patterns = [
    // export [default] [async] function Name
    { kind: 'fn', regex: /^\s*export\s+(?:default\s+)?(?:async\s+)?function\s+([A-Za-z0-9_]+)/ },
    // export const Name = [async] (...) => หรือ function
    { kind: 'const/fn', regex: /^\s*export\s+const\s+([A-Za-z0-9_]+)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z0-9_]+)\s*=>/ },
    // export class Name
    { kind: 'class', regex: /^\s*export\s+(?:default\s+)?class\s+([A-Za-z0-9_]+)/ },
    // export interface / type Name
    { kind: 'type', regex: /^\s*export\s+(?:interface|type)\s+([A-Za-z0-9_]+)/ },
    // export const Name (ทั่วไป เช่น Zod Schema หรือ Config)
    { kind: 'const', regex: /^\s*export\s+const\s+([A-Za-z0-9_]+)\s*(?::[^=]+)?=/ },
    // Non-exported top-level component/helper ในไฟล์ page/layout
    { kind: 'local-fn', regex: /^(?:async\s+)?function\s+([A-Za-z0-9_]+)\s*\(/ }
  ];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    for (const { kind, regex } of patterns) {
      const match = line.match(regex);
      if (match) {
        const name = match[1];
        const startLine = i + 1;
        const endLine = findBlockEndLine(lines, i);
        symbols.push({ kind, name, startLine, endLine });
        break; // ข้าม pattern อื่นในบรรทัดเดียวกัน
      }
    }
  }

  return { totalLines: lines.length, symbols };
}

/**
 * เดินสำรวจโฟลเดอร์แบบ Recursive
 */
function walkDirectory(dirPath, fileList = []) {
  if (!fs.existsSync(dirPath)) return fileList;
  const entries = fs.readdirSync(dirPath, { withFileTypes: true });

  for (const entry of entries) {
    if (IGNORE_DIRS.has(entry.name)) continue;
    const fullPath = path.join(dirPath, entry.name);

    if (entry.isDirectory()) {
      walkDirectory(fullPath, fileList);
    } else if (entry.isFile() && VALID_EXTS.has(path.extname(entry.name))) {
      fileList.push(fullPath);
    }
  }
  return fileList;
}

function generateMarkdown() {
  const now = new Date().toISOString().replace('T', ' ').substring(0, 19);
  const out = [
    '# 📑 CODEBASE NAVIGATION INDEX',
    `> **Auto-generated by \`npm run index:sync\`** | อัปเดตล่าสุด: \`${now}\``,
    '> **คำแนะนำสำหรับ AI Agent:** ใช้พิกัด `[Lเริ่ม-Lจบ]` ด้านล่างคู่กับพารามิเตอร์ `StartLine` และ `EndLine` เสมอ ห้ามเปิดอ่านไฟล์ขนาดใหญ่ทั้งไฟล์',
    ''
  ];

  // 1. ส่วนของ Prisma Schema
  const prismaData = parsePrismaSchema(PRISMA_SCHEMA);
  if (prismaData && prismaData.items && prismaData.items.length > 0) {
    out.push(`## 🗄️ Database Schema (\`prisma/schema.prisma\` — ${prismaData.totalLines} lines)`);
    out.push('| ประเภท | ชื่อ Model / Enum | พิกัดบรรทัด (`StartLine`-`EndLine`) |');
    out.push('| :--- | :--- | :--- |');
    for (const item of prismaData.items) {
      out.push(`| \`${item.kind}\` | **${item.name}** | \`L${item.startLine}-L${item.endLine}\` |`);
    }
    out.push('');
  }

  // 2. ส่วนของ Source Code ทั้งระบบ
  const discoveredFiles = new Set();
  for (const dir of TARGET_DIRS) {
    const fullDir = path.join(ROOT_DIR, dir);
    for (const file of walkDirectory(fullDir)) {
      discoveredFiles.add(file);
    }
  }

  const sortedFiles = Array.from(discoveredFiles).sort();
  out.push(`## 💻 Application Codebase (${sortedFiles.length} files)`);
  out.push('');

  for (const filePath of sortedFiles) {
    const relPath = path.relative(ROOT_DIR, filePath).replace(/\\/g, '/');
    const { totalLines, symbols } = parseTypeScriptFile(filePath);

    if (symbols.length === 0) {
      out.push(`- **\`${relPath}\`** (${totalLines} lines) — *No top-level named exports*`);
      continue;
    }

    const symbolSummary = symbols
      .map((s) => `\`${s.name}\` [L${s.startLine}-L${s.endLine}]`)
      .join(', ');

    out.push(`- **\`${relPath}\`** (${totalLines} lines): ${symbolSummary}`);
  }

  out.push('');
  fs.writeFileSync(OUTPUT_FILE, out.join('\n'), 'utf8');
  console.log(`✅ อัปเดตไฟล์ CODEBASE_INDEX.md สำเร็จ! (สแกนทั้งหมด ${sortedFiles.length} ไฟล์)`);
}

generateMarkdown();
